"""Append-only JSONL ledger store (stdlib only).

The only write path is :func:`append_entry`, which opens the file in append
mode and writes exactly one new line. Nothing in this module (or the CLI)
rewrites, truncates, or deletes existing lines.
"""

from __future__ import annotations

import json
import os
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from workledger.cli._errors import EXIT_ENV_ERROR, EXIT_USER_ERROR, CliError

ENV_PATH = "WORKLEDGER_PATH"
DEFAULT_PATH = Path(".workledger") / "ledger.jsonl"

REQUIRED_FIELDS = ("agent", "action", "summary")
INPUT_FIELDS = frozenset(REQUIRED_FIELDS) | {"refs", "data"}
GENERATED_FIELDS = frozenset({"id", "timestamp"})


def ledger_path() -> Path:
    """Resolve the ledger file: ``$WORKLEDGER_PATH`` or ``./.workledger/ledger.jsonl``."""
    env = os.environ.get(ENV_PATH)
    return Path(env) if env else DEFAULT_PATH


def now_utc() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


def parse_timestamp(value: str) -> datetime:
    """Parse ISO-8601; a trailing ``Z`` or a naive value is treated as UTC."""
    text = value.strip()
    if text.endswith(("Z", "z")):
        text = text[:-1] + "+00:00"
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError as err:
        raise CliError(
            code=EXIT_USER_ERROR,
            message=f"invalid ISO-8601 timestamp: {value!r}",
            remediation="use e.g. 2026-01-31T12:00:00Z",
        ) from err
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed


def validate_input(raw: Any) -> dict[str, Any]:
    """Validate caller-supplied entry fields; return a clean dict."""
    if not isinstance(raw, dict):
        raise CliError(
            code=EXIT_USER_ERROR,
            message="entry must be a JSON object",
            remediation='pass e.g. \'{"agent":"a","action":"edit","summary":"did x"}\'',
        )
    generated = sorted(set(raw) & GENERATED_FIELDS)
    if generated:
        raise CliError(
            code=EXIT_USER_ERROR,
            message=f"field(s) are generated by the ledger and cannot be supplied: {generated}",
            remediation="remove 'id' / 'timestamp' from the input",
        )
    unknown = sorted(set(raw) - INPUT_FIELDS)
    if unknown:
        raise CliError(
            code=EXIT_USER_ERROR,
            message=f"unknown field(s): {unknown}",
            remediation=f"allowed fields: {sorted(INPUT_FIELDS)}",
        )
    for field in REQUIRED_FIELDS:
        value = raw.get(field)
        if not isinstance(value, str) or not value.strip():
            raise CliError(
                code=EXIT_USER_ERROR,
                message=f"field '{field}' is required and must be a non-empty string",
                remediation=f'add "{field}": "..." to the entry',
            )
    entry: dict[str, Any] = {f: raw[f] for f in REQUIRED_FIELDS}
    refs = raw.get("refs", [])
    if not isinstance(refs, list) or not all(isinstance(r, str) for r in refs):
        raise CliError(
            code=EXIT_USER_ERROR,
            message="field 'refs' must be a list of strings",
            remediation='e.g. "refs": ["abc1234", "path/to/file"]',
        )
    entry["refs"] = refs
    data = raw.get("data", {})
    if not isinstance(data, dict):
        raise CliError(
            code=EXIT_USER_ERROR,
            message="field 'data' must be a JSON object",
            remediation='e.g. "data": {"tests": 12}',
        )
    entry["data"] = data
    return entry


def read_entries(path: Path) -> list[dict[str, Any]]:
    """Read all entries; a missing file is an empty ledger."""
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return []
    except OSError as err:
        raise CliError(
            code=EXIT_ENV_ERROR,
            message=f"cannot read ledger {path}: {err}",
            remediation=f"check permissions or set {ENV_PATH}",
        ) from err
    entries: list[dict[str, Any]] = []
    for lineno, line in enumerate(text.splitlines(), start=1):
        if not line.strip():
            continue
        try:
            obj = json.loads(line)
        except json.JSONDecodeError as err:
            raise CliError(
                code=EXIT_ENV_ERROR,
                message=f"ledger {path} is corrupt at line {lineno}",
                remediation="the ledger is append-only; inspect the file by hand",
            ) from err
        entries.append(obj)
    return entries


def append_entry(path: Path, entry_input: dict[str, Any]) -> dict[str, Any]:
    """Stamp ``id``/``timestamp`` and append one line. Never touches prior lines."""
    entry = {"id": uuid.uuid4().hex, "timestamp": now_utc(), **entry_input}
    line = json.dumps(entry, ensure_ascii=False, separators=(",", ":")) + "\n"
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        fd = os.open(path, os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o644)
        try:
            os.write(fd, line.encode("utf-8"))  # single O_APPEND write per entry
        finally:
            os.close(fd)
    except OSError as err:
        raise CliError(
            code=EXIT_ENV_ERROR,
            message=f"cannot write ledger {path}: {err}",
            remediation=f"check permissions or set {ENV_PATH}",
        ) from err
    return entry
